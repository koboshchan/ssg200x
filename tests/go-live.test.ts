import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {goLiveNow} from "../lib/admin";
import {freshRoom} from "../lib/poker";
test("go live requires server-side admin and records both changed maintenance fields once",()=>{
 const r=freshRoom(),who={id:"host",name:"Host",email:"host@example.test",admin:true};
 r.siteMaintenance=true;
 const original=structuredClone(r);
 assert.throws(()=>goLiveNow(r,{...who,admin:false}),/Administrator/);
 assert.deepEqual(r,original);
 goLiveNow(r,who);
 assert.equal(r.siteMaintenance,false);assert.equal(r.backfillInBackground,true);
 assert.equal(r.auditPending?.length,1);
 const event=r.auditPending![0];
 assert.equal(event.who,who.id);assert.equal(event.what,"backfill-go-live");
 assert.deepEqual(event.old,{manual:true,background:false});
 assert.deepEqual(event.new,{manual:false,background:true});
 goLiveNow(r,who);assert.equal(r.auditPending!.length,1);
 r.siteMaintenance=true;goLiveNow(r,who);assert.equal(r.auditPending!.length,2);
});
test("go live uses existing authenticated CSRF-protected audited CAS route and leaves job state alone",()=>{
 const route=readFileSync("app/api/admin/route.ts","utf8");
 assert.match(route,/ensure\(who.admin/);assert.match(route,/type:z.literal\("backfill-go-live"\)/);
 assert.match(route,/goLiveNow\(r,who\)/);assert.match(route,/repeated/);assert.match(route,/mutate\(r=>/);
 const admin=readFileSync("lib/admin.ts","utf8").split("export function goLiveNow")[1];
 assert.doesNotMatch(admin,/candle_backfill|CANDLE_BACKFILL_DISABLED|currentMonthComplete/);
 const ui=readFileSync("app/history-progress.tsx","utf8");
 assert.match(ui,/maintenance\?\.admin/);
 assert.match(ui,/Go live now \(backfill in background\)/);
});
