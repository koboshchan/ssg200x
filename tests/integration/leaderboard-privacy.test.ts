import {test,after} from "node:test";
import assert from "node:assert/strict";
import {db,closeDatabase,readRoom} from "../../lib/db";
import {mutate} from "../../lib/store";
import {register} from "../../lib/poker";
import {setLeaderboardPrivacy} from "../../lib/privacy-settings";
import {setTradingSettings} from "../../lib/trading-settings";
import {publicRoom} from "../../lib/public";
import {getLeaderboard} from "../../lib/leaderboard-store";
if(!process.env.MONGODB_DB?.startsWith("fakebucks_test_"))throw Error("Requires isolated test DB");
process.env.MONGODB_DB+="_privacy";
after(async()=>{await(await db()).dropDatabase();await closeDatabase();});
test("privacy persists through Mongo reconnect/CAS with public read filtering and opt-in restore",async()=>{
 const a={id:"privacy-a",name:"Alice",email:"a@test",admin:false},b={...a,id:"privacy-b",name:"Bob"};
 await mutate(r=>{register(r,a);register(r,b);});
 assert.equal((await getLeaderboard()).rows.length,2);
 await Promise.all([mutate(r=>setLeaderboardPrivacy(r,a,true)),mutate(r=>setTradingSettings(r,b,"pnl"))]);
 await closeDatabase();
 let room=await readRoom();
 assert.equal(publicRoom(room,a).me.hideFromLeaderboard,true);
 assert.equal(publicRoom(room,b).me.hideFromLeaderboard,false);
 assert.equal(publicRoom(room,b).me.triggerInputMode,"pnl");
 assert.equal(publicRoom(room,b).leaderboard.length,1);
 const rows=(await getLeaderboard()).rows;
 assert.deepEqual(rows.map(row=>[row.rank,row.netWorth]),[[1,100000]]);
 assert.equal(publicRoom(room,{...b,admin:true}).adminUsers.length,2);
 await mutate(r=>setLeaderboardPrivacy(r,a,false));await closeDatabase();
 room=await readRoom();
 assert.equal(publicRoom(room,b).leaderboard.length,2);
 assert.deepEqual((await getLeaderboard()).rows.map(row=>[row.rank,row.netWorth]),[[1,100000],[2,100000]]);
});
