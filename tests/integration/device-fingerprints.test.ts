import {test,after} from "node:test";
import assert from "node:assert/strict";
import {db,closeDatabase} from "../../lib/db";
import {recordFingerprint,adminFingerprintPlayers,MAX_FINGERPRINTS_PER_USER,FINGERPRINT_RETENTION_MS,type DeviceRecord} from "../../lib/device-fingerprints";
if(!process.env.MONGODB_DB?.startsWith("fakebucks_test_"))throw Error("Requires isolated test DB");
process.env.MONGODB_DB+="_fingerprints";
after(async()=>{await(await db()).dropDatabase();await closeDatabase();});
const alice={id:"alice",name:"Alice",email:"a@test",admin:false},bob={...alice,id:"bob",name:"Bob"},admin={...alice,id:"admin",admin:true};
const members=[alice,bob].map(m=>({...m,publicId:"public-"+m.id}));
const hash="a".repeat(64),start=new Date("2026-10-20T10:00:00Z"),later=new Date(start.getTime()+60000);
test("Mongo pipeline preserves first seen, records last seen, strictly caps concurrent hashes and prunes expired entries",async()=>{
 await recordFingerprint(alice,hash,start);
 await recordFingerprint(alice,hash,later);
 await recordFingerprint(bob,hash,later);
 const collection=(await db()).collection<DeviceRecord>("deviceFingerprints");
 const a=(await collection.findOne({_id:alice.id}))!;
 assert.equal(a.devices.length,1);assert.equal(a.devices[0].firstSeen.toISOString(),start.toISOString());assert.equal(a.devices[0].lastSeen.toISOString(),later.toISOString());
 assert.equal(a.expiresAt.getTime(),later.getTime()+FINGERPRINT_RETENTION_MS);
 assert.deepEqual(Object.keys(a).sort(),["_id","devices","expiresAt"]);
 assert.deepEqual(Object.keys(a.devices[0]).sort(),["firstSeen","hash","lastSeen"]);
 const reports=await adminFingerprintPlayers(admin,members,later);
 assert.deepEqual(reports[0].possibleAlts.map(x=>x.name),["Bob"]);
 await assert.rejects(adminFingerprintPlayers(alice,members,later),{status:403});
 await Promise.all(Array.from({length:25},(_,i)=>recordFingerprint(alice,i.toString(16).padStart(64,"0"),later)));
 assert.equal((await collection.findOne({_id:alice.id}))!.devices.length,MAX_FINGERPRINTS_PER_USER);
 const future=new Date(later.getTime()+FINGERPRINT_RETENTION_MS+1);
 await recordFingerprint(alice,hash,future);
 assert.equal((await collection.findOne({_id:alice.id}))!.devices.length,1);
 assert.deepEqual((await collection.findOne({_id:bob.id}))!.devices,[]);
 assert.deepEqual((await adminFingerprintPlayers(admin,members,future))[0].possibleAlts,[]);
 const indexes=await collection.indexes();assert.equal(indexes.find(i=>i.name==="expiresAt_1")?.expireAfterSeconds,0);
});
