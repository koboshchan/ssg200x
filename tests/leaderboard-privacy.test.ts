import {test} from "node:test";
import assert from "node:assert/strict";
import {freshRoom,register} from "../lib/poker";
import {hideFromLeaderboard,setLeaderboardPrivacy} from "../lib/privacy-settings";
import {setTradingSettings} from "../lib/trading-settings";
import {leaderboardSnapshot} from "../lib/leaderboard";
import {publicRoom} from "../lib/public";
// @ts-expect-error runtime JavaScript has no generated declarations
import {marketPayload} from "../runtime/market-payload.mjs";
const alice={id:"privacy-alice",name:"Alice",email:"a@test",admin:false};
const bob={...alice,id:"privacy-bob",name:"Bob"};
test("legacy accounts stay visible; hide/restore filters both server standings before ranking without losing settings",()=>{
 const room=freshRoom(),a=register(room,alice),b=register(room,bob);
 a.wallet=200000;
 assert.equal(hideFromLeaderboard(a),false);
 assert.deepEqual(leaderboardSnapshot(room).rows.map(x=>[x.rank,x.name]),[[1,"Alice"],[2,"Bob"]]);
 setTradingSettings(room,alice,"pnl");
 setLeaderboardPrivacy(room,alice,true);
 setTradingSettings(room,alice,"price");
 assert.equal(hideFromLeaderboard(a),true);
 assert.equal(hideFromLeaderboard(b),false);
 const restored=JSON.parse(JSON.stringify(room));
 assert.deepEqual(leaderboardSnapshot(restored).rows.map(x=>[x.rank,x.name]),[[1,"Bob"]]);
 assert.deepEqual(publicRoom(restored,bob).leaderboard.map(x=>x.name),["Bob"]);
 assert.deepEqual(marketPayload(restored,alice.id).leaderboard.map((x:{name:string})=>x.name),["Bob"]);
 assert.equal(marketPayload(restored,alice.id).wallet,a.wallet);
 assert.equal(publicRoom(restored,alice).me.hideFromLeaderboard,true);
 assert.equal(publicRoom(restored,bob).me.hideFromLeaderboard,false);
 assert.equal(publicRoom(restored,{...bob,admin:true}).adminUsers.length,2);
 const before=structuredClone(room);
 for(const value of ["true",null,1,undefined])assert.throws(()=>setLeaderboardPrivacy(room,alice,value as unknown as boolean));
 assert.deepEqual(room,before);
 setLeaderboardPrivacy(restored,alice,false);
 assert.deepEqual(leaderboardSnapshot(restored).rows.map(x=>[x.rank,x.name]),[[1,"Alice"],[2,"Bob"]]);
 assert.equal(restored.members[0].settings.triggerInputMode,"price");
 assert.equal(marketPayload(restored,bob.id).leaderboard.length,2);
 setLeaderboardPrivacy(restored,alice,true);setLeaderboardPrivacy(restored,bob,true);
 assert.deepEqual(leaderboardSnapshot(restored).rows,[]);
 assert.deepEqual(publicRoom(restored,alice).leaderboard,[]);
});
